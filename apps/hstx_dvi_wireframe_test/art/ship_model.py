#!/usr/bin/env python3
# Generates the Cobra Mk III wireframe in ../src/ship_model.c from its corners.
# The faces and edges of the hull are found from the convex hull of the corners,
# so each edge knows the two faces it joins, for hiding the edges at the back.
# The engines and gun are added as extra edges on the faces they sit on.
#
# python3 art/ship_model.py

import itertools
import math
import os

# The corners of the hull, x right, y up, z forwards, as in the original game
HULL = [
	(32, 0, 76), (-32, 0, 76), (0, 26, 24), (-120, -3, -8), (120, -3, -8),
	(-88, 16, -40), (88, 16, -40), (128, -8, -40), (-128, -8, -40),
	(0, 26, -40), (-32, -24, -40), (32, -24, -40),
]

# Details: (name, corners, closed loop?, colour)
DETAILS = [
	("left engine", [(-36, 8, -40), (-8, 12, -40), (-8, -16, -40), (-36, -12, -40)], True, 1),
	("right engine", [(8, 12, -40), (36, 8, -40), (36, -12, -40), (8, -16, -40)], True, 1),
	("left vent", [(-80, 6, -40), (-88, 0, -40), (-80, -6, -40)], True, 2),
	("right vent", [(80, 6, -40), (88, 0, -40), (80, -6, -40)], True, 2),
	("gun", [(0, 0, 76), (0, 0, 90)], False, 2),
]

EPS = 1e-6
# How close two faces have to be to flat to have no edge between them
CREASE = 0.999


def sub(a, b):
	return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def cross(a, b):
	return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def dot(a, b):
	return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def norm(a):
	l = math.sqrt(dot(a, a))
	return (a[0] / l, a[1] / l, a[2] / l)


def hull_faces(pts):
	# Every plane through 3 corners with all the others behind it is a face
	faces = []
	for i, j, k in itertools.combinations(range(len(pts)), 3):
		n = cross(sub(pts[j], pts[i]), sub(pts[k], pts[i]))
		if dot(n, n) < EPS:
			continue
		n = norm(n)
		d = dot(n, pts[i])
		side = [dot(n, p) - d for p in pts]
		if all(s <= 1e-6 for s in side):
			pass
		elif all(s >= -1e-6 for s in side):
			n, d = (-n[0], -n[1], -n[2]), -d
		else:
			continue
		on = frozenset(m for m, p in enumerate(pts) if abs(dot(n, p) - d) < 1e-6)
		if all(f[2] != on for f in faces):
			faces.append((n, d, on))
	return faces


def face_edges(pts, n, on):
	# The outline of a face, from the corners on it in order round its middle
	on = list(on)
	c = [sum(pts[m][a] for m in on) / len(on) for a in range(3)]
	u = norm(sub(pts[on[0]], c))
	v = cross(n, u)
	on.sort(key=lambda m: math.atan2(dot(sub(pts[m], c), v), dot(sub(pts[m], c), u)))
	return [tuple(sorted((on[i], on[(i + 1) % len(on)]))) for i in range(len(on))]


def face_of(faces, p):
	return [i for i, f in enumerate(faces) if abs(dot(f[0], p) - f[1]) < 1e-6]


def main():
	verts = list(HULL)
	faces = hull_faces(HULL)
	edges = {}
	for fi, (n, d, on) in enumerate(faces):
		for e in face_edges(HULL, n, on):
			edges.setdefault(e, []).append(fi)
	out_edges = []
	for (a, b), fs in sorted(edges.items()):
		assert len(fs) == 2, (a, b, fs)
		# Faces that are all but flat to each other are one face with a slight bend, so no edge
		if dot(faces[fs[0]][0], faces[fs[1]][0]) > CREASE:
			continue
		out_edges.append((a, b, fs[0], fs[1], 0))

	for name, corners, loop, colour in DETAILS:
		idx = []
		for p in corners:
			if p not in verts:
				verts.append(p)
			idx.append(verts.index(p))
		# The faces the detail sits on, all of them for the gun on the nose edge
		fs = sorted(set.intersection(*[set(face_of(faces, p)) for p in corners]) or set(face_of(faces, corners[0])))
		assert 1 <= len(fs) <= 2, (name, fs)
		f0, f1 = fs[0], fs[-1]
		pairs = list(zip(idx, idx[1:])) + ([(idx[-1], idx[0])] if loop else [])
		for a, b in pairs:
			out_edges.append((a, b, f0, f1, colour))

	out = [
		"// Generated by art/ship_model.py, edit that and run it again",
		'#include "ship_model.h"',
		"",
		f"static const WireVertex_t _vertices[{len(verts)}] = {{",
	]
	out += [f"\t{{ {x}, {y}, {z} }}," for x, y, z in verts]
	out += ["};", "", "// The normal of each face, pointing out, and a corner on it",
		f"static const WireFace_t _faces[{len(faces)}] = {{"]
	for n, d, on in faces:
		out.append(f"\t{{ {n[0]:.4f}f, {n[1]:.4f}f, {n[2]:.4f}f, {min(on)} }},")
	out += ["};", "", "// The corners each edge joins, the faces either side of it and its colour",
		f"static const WireEdge_t _edges[{len(out_edges)}] = {{"]
	out += [f"\t{{ {a}, {b}, {f0}, {f1}, {c} }}," for a, b, f0, f1, c in out_edges]
	out += ["};", "",
		"const WireModel_t ship_cobra = {",
		f"\t_vertices, _faces, _edges, {len(verts)}, {len(faces)}, {len(out_edges)}",
		"};"]
	path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "ship_model.c")
	with open(path, "w") as f:
		f.write("\n".join(out) + "\n")
	print(f"{len(verts)} corners, {len(faces)} faces, {len(out_edges)} edges")


if __name__ == "__main__":
	main()
