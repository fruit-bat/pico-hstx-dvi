// For writing them shortly
#define ALWAYS { IF_ALWAYS, 0, 0 }
#define WHEN(w, a) { w, a, 0 }
#define OPS(...) ((const StoryOp_t[]){ __VA_ARGS__, { OP_END, 0, 0 } })
#define OP(o, a) { o, a, 0 }
#define OP2(o, a, b) { o, a, b }
#define CHOOSE(label, when, ops, next) { label, when, ops, next }
#define THEN(ops, next) { NULL, ALWAYS, ops, next }
#define NO_CHOICE { NULL, ALWAYS, NULL, 0 }
#define EXIT(ev, place, arg, when, who, text, c0, c1) { ev, place, arg, when, who, text, { c0, c1 } }
#define STEP(...) { (const StoryExit_t[]){ __VA_ARGS__ }, sizeof((const StoryExit_t[]){ __VA_ARGS__ }) / sizeof(StoryExit_t) }

